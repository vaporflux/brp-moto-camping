"""Unified stop model for campgrounds and fuel exits.

The shipped data invites one specific mistake: reading fuel.json's `confidence` as if
it answered "can I use this stop?". It does not. Confidence answers "does a pump exist
here?" -- a claim about the world. Reachability answers "can I get there in 2026?" -- a
claim about the road network. They are independent, and every combination occurs:

    MP 248.1 Laurel Springs   unverified + reachable    (on every exit list, no station)
    MP 330.9 Spruce Pine      verified   + unreachable  (stranded in the orphan segment)
    MP 344.1 NC 80            likely     + unreachable  (inside the Helene closure)

Collapsing these into one score hides exactly the cases that strand a rider, so this
module keeps both axes and derives a display grade from the pair.
"""
import re

from . import geo

ACCESS_EN_ROUTE = "en_route"          # access milepost sits on open Parkway
ACCESS_VIA_DETOUR = "detour_access"   # inside a closure that has a signed detour
ACCESS_OFF_PARKWAY = "off_parkway_only"  # inside a severing closure; surface roads only

# Straight-line station distance is a LOWER BOUND on road distance, never an estimate of
# it. Checked across the 28 records carrying both numbers, the published/straight ratio
# ranges 0.15-3.57 with median 1.36 -- there is no stable sinuosity factor to apply, so
# this module does not invent one. It reports both numbers and plans against the larger.
#
# The ratio does yield one hard test: the crow-flies distance cannot exceed the road
# distance. A record where it does is self-contradictory -- either OSM missed a nearer
# station or the Parkway anchor is misplaced -- and must not be quietly averaged away.


def _parse_published(text):
    """Numeric (low, high) mileage from an exit-list distance string, or None."""
    if not text:
        return None
    found = re.findall(r"(\d+(?:\.\d+)?)\s*(?:-\s*(\d+(?:\.\d+)?))?\s*mi", text)
    if not found:
        return None
    vals = []
    for lo, hi in found:
        vals.append(float(lo))
        if hi:
            vals.append(float(hi))
    return min(vals), max(vals)


def _classify_access(net, stop_mp):
    """Where a stop sits relative to the rideable network.

    A stop inside a closure that has a signed detour is still served by the component
    on either side -- the detour rejoins the same road. Leaving its component as None
    would silently drop it from fuel-gap arithmetic and manufacture a phantom gap.
    """
    seg = net.segment_at_mp(stop_mp)
    if seg is not None:
        return ACCESS_EN_ROUTE, seg.component, None
    for gap in net.closures:
        if gap["from_mp"] <= stop_mp <= gap["to_mp"]:
            if gap["severs"]:
                return ACCESS_OFF_PARKWAY, None, gap
            before = net.segment_at_mp(gap["from_mp"] - 0.05)
            after = net.segment_at_mp(gap["to_mp"] + 0.05)
            comp = (before or after).component if (before or after) else None
            return ACCESS_VIA_DETOUR, comp, gap
    return ACCESS_OFF_PARKWAY, None, None


def build_campgrounds(model, net, raw):
    out = []
    for c in raw:
        mp = float(c["mp"])
        access, comp, gap = _classify_access(net, mp)
        i, off = geo.nearest_vertex(model.pts, c["lat"], c["lon"])

        # A campground's `mp` is the milepost of its Parkway access, not its location.
        # A closure at that milepost blocks the *approach from the Parkway*; it does not
        # delete the campground, which sits on a surface road and usually stays open.
        rec = dict(c)
        rec.update({
            "kind": "campground",
            "mp": mp,
            "access_class": access,
            "component": comp,
            "off_parkway_mi": round(off, 2),
            "nearest_centerline_mp": round(model.mp_at_index(i), 2),
            "reachable": True,   # surface-road businesses; closure affects approach only
            "reachable_from_parkway": access == ACCESS_EN_ROUTE,
            "blocking_closure": ({"from_mp": gap["from_mp"], "to_mp": gap["to_mp"],
                                  "reason": gap["reason"], "detour": gap["detour"]}
                                 if gap else None),
        })
        out.append(rec)
    return sorted(out, key=lambda r: r["mp"])


def build_fuel(model, net, raw):
    out = []
    for f in raw:
        mp = float(f["mp"])
        access, comp, gap = _classify_access(net, mp)
        stations = f.get("stations", [])

        # Backfill the Parkway anchor. Every NC record ships without one; the VA anchors
        # that do exist were generated by walking the uncalibrated model, so they carry
        # its 1-3 mi error. Recomputing all of them under the calibrated model makes the
        # whole dataset consistent and correct rather than half-consistent and wrong.
        lat, lon = model.coord_at_mp(mp)

        detours = []
        for s in stations:
            if s.get("lat") is not None and s.get("lon") is not None:
                d = geo.haversine((lat, lon), (s["lat"], s["lon"]))
                detours.append(round(d, 2))
            else:
                detours.append(None)
        known = [d for d in detours if d is not None]
        straight = min(known) if known else None
        pub = _parse_published(f.get("published_distance"))
        conflict = (straight is not None and pub is not None
                    and straight > pub[1] * 1.05)
        # Plan against the worse of the two sources. Under-promising a detour strands
        # nobody; over-promising one does.
        candidates = [d for d in (straight, pub[1] if pub else None) if d is not None]
        detour_plan = round(max(candidates), 1) if candidates else None

        rec = dict(f)
        rec.update({
            "kind": "fuel",
            "mp": mp,
            "parkway_lat": round(lat, 6),
            "parkway_lon": round(lon, 6),
            "parkway_anchor_source": "derived_from_calibrated_milepost",
            "access_class": access,
            "component": comp,
            "station_detour_mi": detours,
            "straight_line_mi": round(straight, 2) if straight is not None else None,
            "published_mi": list(pub) if pub else None,
            "detour_plan_mi": detour_plan,
            "detour_round_trip_mi": (round(detour_plan * 2, 1)
                                     if detour_plan is not None else None),
            "distance_conflict": conflict,
            "has_station": len(stations) > 0,
            "reachable_from_parkway": access != ACCESS_OFF_PARKWAY,
            "blocking_closure": ({"from_mp": gap["from_mp"], "to_mp": gap["to_mp"],
                                  "reason": gap["reason"], "detour": gap["detour"]}
                                 if gap else None),
        })
        rec["plan_grade"] = _fuel_grade(rec)
        out.append(rec)
    return sorted(out, key=lambda r: r["mp"])


def _fuel_grade(rec):
    """Display grade over BOTH axes. Never collapses them -- the UI shows the reason.

    A signed detour around a 0.4 mi bridge closure does not make a fuel stop
    unreachable; it makes it cost a few extra miles. Only a severing closure, with no
    way back onto the Parkway, actually removes a stop.
    """
    if rec["access_class"] == ACCESS_OFF_PARKWAY:
        return "unreachable"
    if not rec["has_station"] or rec["confidence"] == "unverified":
        return "do_not_rely"
    if rec["confidence"] == "likely":
        return "unconfirmed"
    if rec["access_class"] == ACCESS_VIA_DETOUR:
        return "usable_via_detour"
    return "usable"


USABLE_GRADES = ("usable", "usable_via_detour", "unconfirmed")


def fuel_gaps(fuel, net, component=None, max_detour_mi=None):
    """Consecutive-usable-fuel gaps, measured only where a rider can actually ride.

    Gaps are computed per connected component. Measuring across the Helene break would
    invent a 70-mile gap on a stretch nobody can ride, and hide the real one.

    max_detour_mi drops exits that cost more to reach than the rider will accept. This
    is what turns MP 411.8 -- a real station 12-18 mi off the road -- from something
    that silently closes the 49.5 mi Asheville-Balsam gap into something the rider has
    to opt into.
    """
    gaps = []
    usable = [f for f in fuel if f["plan_grade"] in USABLE_GRADES]
    if max_detour_mi is not None:
        usable = [f for f in usable
                  if f["detour_plan_mi"] is None
                  or f["detour_plan_mi"] <= max_detour_mi]
    for cid, comp in sorted(net.components.items()):
        if component is not None and cid != component:
            continue
        inside = [f for f in usable if f["component"] == cid]
        marks = list(inside)
        if not inside or inside[0]["mp"] - comp["from_mp"] > 0.05:
            marks.insert(0, {"mp": comp["from_mp"], "name": "start of open Parkway",
                             "edge": True})
        if not inside or comp["to_mp"] - inside[-1]["mp"] > 0.05:
            marks.append({"mp": comp["to_mp"], "name": "end of open Parkway",
                          "edge": True})
        for a, b in zip(marks, marks[1:]):
            gaps.append({
                "component": cid,
                "from_mp": round(a["mp"], 1), "to_mp": round(b["mp"], 1),
                "gap_mi": round(b["mp"] - a["mp"], 1),
                "from_name": a.get("town") or a.get("name"),
                "to_name": b.get("town") or b.get("name"),
                "from_is_edge": a.get("edge", False),
                "to_is_edge": b.get("edge", False),
            })
    return sorted(gaps, key=lambda g: -g["gap_mi"])
